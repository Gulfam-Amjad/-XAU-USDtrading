export function normalizeSymbol(raw: unknown): SymbolCode {
  const up = String(raw ?? "XAUUSD").toUpperCase().replace(/[^A-Z]/g, "");
  return (SYMBOLS as string[]).includes(up) ? (up as SymbolCode) : "XAUUSD";
}

// USD P&L generated by a 1.0 price-unit move on 1.00 standard lot.
export function usdPerPriceUnit(symbol: SymbolCode, refPrice: number): number {
  const spec = SYMBOL_SPECS[symbol];
  if (spec.quoteCurrency === "JPY") {
    return spec.contractSize / Math.max(80, refPrice || 155);
  }
  return spec.contractSize;
}

export function formatPrice(symbol: SymbolCode, price: number | null | undefined): string {
  if (price === null || price === undefined || !Number.isFinite(price)) return "--";
  return price.toFixed(SYMBOL_SPECS[symbol].decimals);
}

export function marginRequiredUsd(symbol: SymbolCode, lots: number, entryPrice: number): number {
  const spec = SYMBOL_SPECS[symbol];
  const notionalUsd =
    spec.quoteCurrency === "JPY"
      ? lots * spec.contractSize // USD is base currency on USDJPY
      : lots * spec.contractSize * entryPrice;
  return Math.round((notionalUsd / spec.leverage) * 100) / 100;
}

export function pnlForLots(
  symbol: SymbolCode,
  side: Side,
  entry: number,
  exitPrice: number,
  lots: number,
): number {
  const move = side === "BUY" ? exitPrice - entry : entry - exitPrice;
  const perUnit = usdPerPriceUnit(symbol, exitPrice || entry);
  return Math.round(move * lots * perUnit * 100) / 100;
}
